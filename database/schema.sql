CREATE TABLE IF NOT EXISTS public.categorias (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.insumos (
    id_insumo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL CHECK (length(trim(nombre)) > 0),
    marca VARCHAR(80) NOT NULL CHECK (length(trim(marca)) > 0),
    stock_actual INTEGER NOT NULL DEFAULT 0 CHECK (stock_actual >= 0),
    stock_minimo INTEGER NOT NULL DEFAULT 3 CHECK (stock_minimo >= 0),
    id_categoria INTEGER REFERENCES public.categorias(id_categoria) ON DELETE SET NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_insumos_id_categoria
    ON public.insumos (id_categoria);

INSERT INTO public.categorias (nombre)
VALUES ('Tinturas'), ('Oxidantes'), ('Champús y Tratamientos')
ON CONFLICT (nombre) DO NOTHING;

ALTER TABLE public.categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.insumos ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS categorias_lectura_publica ON public.categorias;
CREATE POLICY categorias_lectura_publica
    ON public.categorias
    FOR SELECT
    TO anon
    USING (true);

DROP POLICY IF EXISTS insumos_acceso_publico ON public.insumos;
CREATE POLICY insumos_acceso_publico
    ON public.insumos
    FOR ALL
    TO anon
    USING (true)
    WITH CHECK (true);

GRANT SELECT ON TABLE public.categorias TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.insumos TO anon;
GRANT USAGE, SELECT ON SEQUENCE public.categorias_id_categoria_seq TO anon;
GRANT USAGE, SELECT ON SEQUENCE public.insumos_id_insumo_seq TO anon;

CREATE OR REPLACE FUNCTION public.descontar_stock(p_id_insumo INTEGER)
RETURNS VOID
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
BEGIN
    UPDATE public.insumos
    SET stock_actual = stock_actual - 1
    WHERE id_insumo = p_id_insumo
      AND stock_actual > 0;

    IF FOUND THEN
        RETURN;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.insumos
        WHERE id_insumo = p_id_insumo
    ) THEN
        RAISE EXCEPTION 'Stock insuficiente para realizar el descuento.'
            USING ERRCODE = '23514';
    END IF;

    RAISE EXCEPTION 'Insumo no encontrado.'
        USING ERRCODE = 'P0002';
END;
$$;

REVOKE ALL ON FUNCTION public.descontar_stock(INTEGER) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.descontar_stock(INTEGER) TO anon;
